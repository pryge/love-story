export const getGreetingPartsByHour = (
  hour: number = new Date().getHours(),
): GreetingParts => {
  if (hour >= 22 || hour < 6) {
    return {
      prefix: 'Нічний щоденник кохання 🌙',
      accent: 'чому моя принцеса ще не спить? ♥',
      subtext: 'Ніч така лагідна і затишна, як твої обійми...',
    };
  }
  if (hour >= 6 && hour < 12) {
    return {
      prefix: 'Доброго ранку,',
      accent: 'моє сонечко ☀️',
      subtext: 'Нехай твій день буде сповнений усмішок та тепла.',
    };
  }
  if (hour >= 12 && hour < 18) {
    return {
      prefix: 'Затишного дня,',
      accent: 'моя принцеса 🌸',
      subtext: 'Просто нагадую, як сильно я тебе кохаю.',
    };
  }
  return {
    prefix: 'Теплого вечора,',
    accent: 'кохана 🌙',
    subtext: 'Час для відпочинку та затишних обіймів.',
  };
};
